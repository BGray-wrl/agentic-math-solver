#!/usr/bin/env python3
"""
Merge new branches from the extend-scaling run with the existing
`results/dataset_20260505.jsonl` scaling rows, then rebuild the scaling bucket
at `results/scaling_20260506/` with pass@n for n in {1, 3, 5, 7, 9} on the
canonical 70-problem PB+R26 set for all 5 cells:

  ('scaling',           'gemma-4-31b-it',     'default')
  ('scaling',           'gpt-oss-120b',       'default')
  ('scaling_reasoning', 'gemma-4-31b-it',     'max')
  ('scaling_reasoning', 'gpt-oss-120b',       'max')
  ('scaling_v4flash',   'deepseek-v4-flash',  'default')

Coverage policy
---------------
- Existing scaling/scaling_reasoning/scaling_v4flash branches are kept verbatim.
- For ('scaling', gemma|gpt-oss, default) on the 40 problems missing from the
  original scaling source, we fold in phase1 'generate'-condition branches
  (already v4flash-judged with default reasoning).
- New branches generated by extend_scaling_pass9_20260507 are appended.

Outputs
-------
  results/scaling_20260506/trials.jsonl   (rebuilt; one row per cell × pid × n)
  results/scaling_20260506/trials.csv
  results/scaling_20260506/summary.csv    (one row per cell × n)
  results/scaling_20260506/data_dictionary.md (n=9 added)
  results/scaling_20260506/report.md      (headline table includes n=9)

Usage
-----
  uv run experiments/merge_scaling_pass9_20260507.py --run-dir <run-dir>
"""

