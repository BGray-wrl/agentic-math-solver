def build(existing: dict, new: dict, problems: dict) -> tuple[list[dict], list[dict]]:
    """Returns (trials_rows, summary_rows). One trial row per (cell, pid, n)."""
    trials: list[dict] = []

    for src, model, rsn in CELLS:
        cell_key = (src, model, rsn)
        cell_existing = existing.get(cell_key, {})
        cell_new = new.get(cell_key, {})
        for pid in sorted(set(cell_existing.keys()) | set(cell_new.keys())):
            payload = cell_existing.get(pid)
            ex_branches = (payload or {}).get("branches", [])
            new_branches = cell_new.get(pid, [])
            # Combine, sort by k, dedup at same k. Prefer the entry with a non-null
            # v4flash_score: existing branches usually win, but a backfilled new
            # branch should override an existing slot whose v4flash judge was missing.
            by_k: dict = {}
            for b in ex_branches + new_branches:
                k = b.get("k")
                cur = by_k.get(k)
                if cur is None or (cur.get("v4flash_score") is None and b.get("v4flash_score") is not None):
                    by_k[k] = b
            combined = list(by_k.values())
            combined.sort(key=lambda b: (b.get("k") if b.get("k") is not None else 999))
            v4f = [b["v4flash_score"] for b in combined]
            v4p = [b["v4pro_score"] for b in combined]
            gem = [b["gemini_score"] for b in combined]

            row_meta = (payload or {}).get("row_meta", {})
            level = row_meta.get("level")
            ann = diff_annotate(pid, level)
            problem = problems.get(pid, {})

            for n in N_VALUES:
                mean_f, std_f, k_subs_f, pr = resample_pass_at_n(v4f, n)
                mean_p, std_p, _, _ = resample_pass_at_n(v4p, n)
                mean_g, std_g, _, _ = resample_pass_at_n(gem, n)
                trials.append({
                    "experiment": "scaling",
                    "source_experiment": src,
                    "model_id": model,
                    "model_short": model_short(model),
                    "reasoning": rsn,
                    "problem_id": pid,
                    "level": level,
                    "difficulty": ann["difficulty"],
                    "difficulty_label": ann["difficulty_label"],
                    "is_26_research": pid in FRONTIER_DIFFICULTY,
                    "n": n,
                    "branches_available": len(combined),
                    "subsets_used": k_subs_f,
                    "pass_at_n_mean_v4flash": mean_f,
                    "pass_at_n_std_v4flash": std_f,
                    "pass_at_n_pass_rate_v4flash": pr,
                    "pass_at_n_mean_v4pro": mean_p,
                    "pass_at_n_std_v4pro": std_p,
                    "pass_at_n_mean_gemini": mean_g,
                    "pass_at_n_std_gemini": std_g,
                    "branch_scores_v4flash": v4f,
                    "branch_scores_v4pro": v4p,
                    "branch_scores_gemini": gem,
                    "branch_origins": [b["source_origin"] for b in combined],
                })

    # Summary: one row per (src, model_short, reasoning, n)
    groups: dict = defaultdict(list)
    for r in trials:
        groups[(r["source_experiment"], r["model_short"], r["reasoning"], r["n"])].append(r)

    def _safe_mean(xs): xs = [x for x in xs if x is not None]; return round(mean(xs), 4) if xs else None
    def _safe_pstdev(xs): xs = [x for x in xs if x is not None]; return round(pstdev(xs), 4) if len(xs) > 1 else (0.0 if xs else None)

    summary_rows = []
    for (src, ms, rsn, n), grp in sorted(groups.items()):
        means = [g["pass_at_n_mean_v4flash"] for g in grp]
        prs = [g["pass_at_n_pass_rate_v4flash"] for g in grp if g["pass_at_n_pass_rate_v4flash"] is not None]
        imo = [g["pass_at_n_mean_v4flash"] for g in grp if g["difficulty"] == 1]
        research = [g["pass_at_n_mean_v4flash"] for g in grp if (g["difficulty"] or 0) >= 2]
        research_solves = sum(1 for g in grp if (g["difficulty"] or 0) >= 2
                              and g["pass_at_n_mean_v4flash"] is not None
                              and g["pass_at_n_mean_v4flash"] >= PASS_THRESHOLD)
        summary_rows.append({
            "source_experiment": src,
            "model_short": ms,
            "reasoning": rsn,
            "n": n,
            "n_problems": len(grp),
            "mean_pass_at_n_v4flash": _safe_mean(means),
            "std_pass_at_n_v4flash": _safe_pstdev(means),
            "pass_rate_v4flash": round(mean(prs), 4) if prs else None,
            "mean_score_imo": _safe_mean(imo),
            "mean_score_research": _safe_mean(research),
            "research_solves": research_solves,
        })
    return trials, summary_rows


