def main():
    p = argparse.ArgumentParser()
    p.add_argument("--run-dir", required=True, help="Run dir from extend_scaling_pass9_20260507.")
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args()

    run_dir = Path(args.run_dir)
    if not run_dir.exists():
        raise SystemExit(f"Run dir not found: {run_dir}")

    sys.path.insert(0, str(ROOT / "experiments"))
    from problemset_70 import load_70_problems
    problems = load_70_problems()

    print("Loading v4flash backfill (if any)...", flush=True)
    v4f_backfill = load_v4flash_backfill(run_dir)
    print(f"  {len(v4f_backfill)} backfilled scores")
    print("Loading existing branches from dataset...", flush=True)
    existing = load_existing(CELLS, v4f_backfill=v4f_backfill)
    print("Loading new branches from run dir...", flush=True)
    new = load_new_branches(run_dir)

    # Stats
    print("\nExisting branches per cell × pid count:")
    for cell_key, pid_map in existing.items():
        m_counts = sorted({len(p["branches"]) for p in pid_map.values()})
        print(f"  {cell_key}: pids={len(pid_map)}, distinct branch-counts={m_counts}")
    print("\nNew branches per cell × pid count:")
    for cell_key, pid_map in new.items():
        m_counts = sorted({len(bs) for bs in pid_map.values()})
        print(f"  {cell_key}: pids={len(pid_map)}, distinct branch-counts={m_counts}")

    print("\nBuilding trials + summary...", flush=True)
    trials, summary = build(existing, new, problems)
    print(f"  {len(trials)} trial rows, {len(summary)} summary rows")

    # Coverage report
    print("\nPer-cell branches_available distribution at n=1:")
    by_cell = defaultdict(list)
    for r in trials:
        if r["n"] == 1:
            by_cell[(r["source_experiment"], r["model_short"], r["reasoning"])].append(r["branches_available"])
    for k, vs in sorted(by_cell.items()):
        from collections import Counter
        print(f"  {k}: pids={len(vs)}, branches_available={dict(Counter(vs))}")

    if args.dry_run:
        print("\n--dry-run: not writing files.")
        return

    print("\nWriting outputs...", flush=True)
    write_jsonl(BUCKET / "trials.jsonl", trials)
    write_csv(BUCKET / "trials.csv", trials, TRIALS_CSV_COLS)
    write_csv(BUCKET / "summary.csv", summary, SUMMARY_CSV_COLS)
    (BUCKET / "data_dictionary.md").write_text(DATA_DICT)
    write_report(BUCKET / "report.md", summary, trials)
    print("Done.")
    for p in [BUCKET / "trials.jsonl", BUCKET / "trials.csv",
              BUCKET / "summary.csv", BUCKET / "data_dictionary.md",
              BUCKET / "report.md"]:
        print(f"  {p}")


