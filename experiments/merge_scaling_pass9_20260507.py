# Read new branches from the extend-scaling run
# ============================================================================

def load_new_branches(run_dir: Path) -> dict:
    """Returns {(src, model, reasoning): {pid: [{k, v4flash_score, ...}]}}."""
    out: dict = {}
    branches_root = run_dir / "branches"
    if not branches_root.exists():
        return out
    for src_dir in sorted(branches_root.iterdir()):
        if not src_dir.is_dir(): continue
        src = src_dir.name
        for model_dir in sorted(src_dir.iterdir()):
            if not model_dir.is_dir(): continue
            ms = model_dir.name
            full_model = {"gemma-4-31b-it": GEMMA, "gpt-oss-120b": OSS, "deepseek-v4-flash": V4F}.get(ms)
            if not full_model: continue
            for pid_dir in sorted(model_dir.iterdir()):
                if not pid_dir.is_dir(): continue
                pid = pid_dir.name
                bs = []
                for kf in sorted(pid_dir.glob("k*.json")):
                    try:
                        with open(kf, encoding="utf-8") as fh:
                            d = json.load(fh)
                        if d.get("error"): continue
                        s = _judge_score(d.get("judges"), "v4flash")
                        bs.append({
                            "k": d.get("k"),
                            "v4flash_score": s,
                            "v4pro_score":  None,
                            "gemini_score": None,
                            "source_origin": f"{src}.new",
                        })
                    except Exception:
                        pass
                if bs:
                    rsn = "max" if src == "scaling_reasoning" else "default"
                    out.setdefault((src, full_model, rsn), {}).setdefault(pid, []).extend(bs)
    return out


# ============================================================================
# pass@n enumeration
# ============================================================================

def resample_pass_at_n(scores: list[int | None], n: int) -> tuple[float | None, float | None, int, float | None]:
    M = len(scores)
    if n > M or M == 0: return (None, None, 0, None)
    maxes = []
    pass_hits = 0
    for combo in combinations(range(M), n):
        sub = [scores[i] for i in combo]
        if any(s is None for s in sub): continue
        m = max(sub)
        maxes.append(m)
        if m >= PASS_THRESHOLD: pass_hits += 1
    if not maxes: return (None, None, 0, None)
    if len(maxes) == 1:
        return (round(float(maxes[0]), 4), 0.0, 1, round(pass_hits / 1, 4))
    return (round(mean(maxes), 4), round(pstdev(maxes), 4), len(maxes), round(pass_hits / len(maxes), 4))


