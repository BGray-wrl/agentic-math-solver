def model_short(m: str) -> str: return m.split("/")[-1]


def _judge_score(judges: dict | None, key: str = "v4flash") -> int | None:
    if not judges: return None
    sub = judges.get(key) or {}
    s = sub.get("score")
    return int(s) if isinstance(s, int) else None


