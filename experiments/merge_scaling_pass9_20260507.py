def load_v4flash_backfill(run_dir: Path) -> dict:
    """Returns {(model_id, pid, k): score} from phase1_v4flash_backfill.json (if present)."""
    p = run_dir / "phase1_v4flash_backfill.json"
    if not p.exists():
        return {}
    with open(p, encoding="utf-8") as f:
        d = json.load(f)
    out = {}
    for key, payload in d.items():
        model, pid, k = key.split("|")
        out[(model, pid, int(k))] = payload.get("score")
    return out


def load_existing(cells: list, v4f_backfill: dict | None = None) -> dict:
    """Returns {(src,model,reasoning): {pid: {'row_meta': dict, 'branches': [{score,verdict_source,k}]}}}.

    For ('scaling', gemma|gpt-oss, default) we additionally fold phase1
    'generate' branches for pids NOT covered in the scaling source.
    """
    cell_keys = {(c[0], c[1]) for c in cells}
    out: dict = {(c[0], c[1], c[2]): {} for c in cells}

    # Map (src, model) -> reasoning, for resolving the cell tuple.
    reasoning_by_cell = {(c[0], c[1]): c[2] for c in cells}

    phase1_generate_pool: dict = {}  # {(model): {pid: {row_meta, branches}}}

    with open(DATASET, encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            exp = r["experiment"]
            model = r["model"]
            pid = r["problem_id"]
            if (exp, model) in cell_keys:
                rsn = reasoning_by_cell[(exp, model)]
                branches = []
                for b in r.get("branches") or []:
                    s = _judge_score(b.get("judges"), "v4flash")
                    branches.append({
                        "k": b.get("k"),
                        "v4flash_score": s,
                        "v4pro_score":  _judge_score(b.get("judges"), "v4pro"),
                        "gemini_score": _judge_score(b.get("judges"), "gemini"),
                        "source_origin": exp,
                    })
                out[(exp, model, rsn)][pid] = {
                    "row_meta": {
                        "level": r.get("level"),
                        "category": r.get("category"),
                        "is_special_10": r.get("is_special_10", False),
                    },
                    "branches": branches,
                }
            elif exp == "phase1" and r.get("condition") == "generate" and model in (GEMMA, OSS):
                bs = []
                for b in r.get("branches") or []:
                    s = _judge_score(b.get("judges"), "v4flash")
                    if s is None and v4f_backfill:
                        s = v4f_backfill.get((model, pid, b.get("k")))
                    bs.append({
                        "k": b.get("k"),
                        "v4flash_score": s,
                        "v4pro_score":  _judge_score(b.get("judges"), "v4pro"),
                        "gemini_score": _judge_score(b.get("judges"), "gemini"),
                        "source_origin": "phase1.generate",
                    })
                phase1_generate_pool.setdefault(model, {})[pid] = {
                    "row_meta": {
                        "level": r.get("level"),
                        "category": r.get("category"),
                        "is_special_10": r.get("is_special_10", False),
                    },
                    "branches": bs,
                }

    # Fold phase1 generate into scaling/gemma|gpt-oss for missing pids.
    for model in (GEMMA, OSS):
        cell_key = ("scaling", model, "default")
        for pid, payload in phase1_generate_pool.get(model, {}).items():
            if pid not in out[cell_key]:
                out[cell_key][pid] = payload
    return out


